public class OperasiMatematika {
    int x;
    int y;

    public int hitungPenjumlahan() {
        return x + y;
    }

    public int hitungPengurangan() {
        return x - y;
    }

    public int hitungPerkalian() {
        return x * y;
    }

    public int hitungPembagian() {
        return x / y;
    }
}
