public class ManipulasiString {
    String a;
    String b;
    
    // ubah string 'a' -> huruf kecil semua (lowercase)
    String ubahKeLowercase() {
        return a.toLowerCase();
    }

    // ubah string 'b' -> huruf kapital semua (uppercase)
    String ubahKeUppercase() {
        return b.toUpperCase();
    }
}
